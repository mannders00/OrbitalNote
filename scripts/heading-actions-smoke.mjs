import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = process.env.BASE_URL || 'http://127.0.0.1:9249';
  await page.goto(base);
  const api = async (method, q = {}) => { const r = await page.request.post(base + '/api', { data: { method, ...q } }); assert.ok(r.ok(), await r.text()); return r.json(); };
  const state = await api('Status'), path = 'heading-menu-smoke.org';
  const old = state.files.some(f => f.path === path) ? await api('Read', { id: state.id, path }) : null;
  await api('Save', { id: state.id, path, revision: old?.revision || '', source: '* TODO [#B] Plan :work:\n:PROPERTIES:\n:ID: preserve-me\n:OWNER: Morgan\n:END:\nBody stays untouched.\n** Child\nNested body.\n' });
  await page.locator(`#tree [data-open="${path}"]`).click();
  const note = page.locator(`.ui-document[data-path="${path}"]`), editor = note.locator('.ui-source');
  assert.equal(await note.locator('.editor-task-box').count(), 0);
  await editor.locator('.task-state').click(); await editor.locator('.task-state.org-done').waitFor();
  assert.match(await editor.evaluate(el => el.value), /^\* DONE/);
  await editor.locator('.task-state').click(); await editor.locator('.task-state.org-todo').waitFor();
  const menu = async label => {
    const heading = note.locator('.org-heading').first(); await heading.hover();
    await heading.getByRole('button', { name: 'Heading actions', exact: true }).click();
    await page.getByRole('dialog', { name: 'Heading actions' }).getByRole('button', { name: label, exact: true }).click();
  };
  await menu('Edit tags…'); await page.locator('#modal [name="tags"]').fill('research urgent'); await page.locator('#modal [name="tags"]').press('Enter');
  await page.waitForFunction(() => document.querySelector('#source').value.includes(':research:urgent:'));
  await menu('Edit properties…'); await page.locator('#modal [name="name"]').fill('OWNER');
  assert.equal(await page.locator('#modal [name="value"]').inputValue(), 'Morgan');
  await page.locator('#modal [name="value"]').fill('Taylor'); await page.locator('#modal [name="value"]').press('Enter');
  await page.waitForFunction(() => document.querySelector('#source').value.includes(':OWNER: Taylor'));
  assert.match(await editor.evaluate(el => el.value), /:ID: preserve-me\n:OWNER: Taylor\n:END:\nBody stays untouched/);
  await menu('Set priority…'); await page.locator('#modal [name="priority"]').selectOption('A'); await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#source').value.includes('[#A]'));
  await note.locator('.ui-preview-toggle').click();
  await note.locator('.ui-preview .task-state').click();
  await note.locator('.ui-preview .task-state.org-done').waitFor();
  const previewState = await note.locator('.ui-preview .task-state').evaluate(el => getComputedStyle(el).color);
  assert.notEqual(previewState, '');
  await page.locator('#tree [data-open="heading-menu-smoke.org"]').hover();
  await page.getByRole('button', { name: 'Actions for file heading-menu-smoke.org', exact: true }).click();
  const fileMenu = page.getByRole('dialog', { name: 'File actions' });
  assert.equal(await fileMenu.getByRole('button').count(), 3);
  await page.keyboard.press('Escape');
  // A separate disposable, unopened file exercises manager rename and delete.
  const temp = 'manager-' + Date.now() + '.org';
  await api('Save', { id: state.id, path: temp, source: '* Temporary\n', revision: '' });
  await page.locator(`#tree [data-open="${temp}"]`).waitFor();
  await page.locator(`#tree [data-open="${temp}"]`).hover();
  await page.getByRole('button', { name: `Actions for file ${temp}`, exact: true }).click();
  await page.getByRole('dialog', { name: 'File actions' }).getByRole('button', { name: 'Rename or move…', exact: true }).click();
  const renamed = temp.replace('.org', '-renamed.org');
  await page.locator('#modal [name="value"]').fill(renamed); await page.locator('#modal [name="value"]').press('Enter');
  await page.locator(`#tree [data-open="${renamed}"]`).waitFor();
  await page.locator(`#tree [data-open="${renamed}"]`).hover();
  await page.getByRole('button', { name: `Actions for file ${renamed}`, exact: true }).click();
  await page.getByRole('dialog', { name: 'File actions' }).getByRole('button', { name: 'Delete file…', exact: true }).click();
  await page.locator('#modal-submit').click();
  await page.locator(`#tree [data-open="${renamed}"]`).waitFor({ state: 'detached' });
  const folder = 'folder-' + Date.now(), moved = folder + '-renamed';
  await api('Mkdir', { id: state.id, path: folder });
  await page.locator(`#tree details[data-path="${folder}"] > summary`).hover();
  await page.locator(`#tree [data-folder="${folder}"]`).click();
  await page.getByRole('dialog', { name: 'Folder actions' }).getByRole('button', { name: 'Rename or move…', exact: true }).click();
  await page.locator('#modal [name="value"]').fill(moved); await page.locator('#modal [name="value"]').press('Enter');
  await page.locator(`#tree details[data-path="${moved}"] > summary`).hover();
  await page.locator(`#tree [data-folder="${moved}"]`).click();
  await page.getByRole('dialog', { name: 'Folder actions' }).getByRole('button', { name: 'Delete empty folder…', exact: true }).click();
  await page.locator('#modal-submit').click();
  await page.locator(`#tree details[data-path="${moved}"]`).waitFor({ state: 'detached' });
  assert.deepEqual(errors, []);
  console.log('PASS: task-state text toggles in edit/read views, heading menus, tags/properties/priority preservation, Enter saves, unopened file rename/delete.');
} finally { await browser.close(); }
