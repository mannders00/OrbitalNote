// Run against a disposable app/dev workspace.
import { chromium, webkit } from 'playwright';
import assert from 'node:assert/strict';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const base = process.env.BASE_URL || 'http://127.0.0.1:9250';
const browser = process.env.BROWSER === 'webkit' ? await webkit.launch() : await chromium.launch({ executablePath: process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const api = async (method, data = {}) => { const response = await page.request.post(base + '/api', { data: { method, ...data } }); assert(response.ok(), await response.text()); return response.json(); };
  const state = await api('Status'), path = 'task-modal-polish.org';
  const previous = state.files.some(file => file.path === path) ? await api('Read', { id: state.id, path }) : null;
  const source = '#+TITLE: Task editor\n* Projects\nParent notes.\n** Existing\nKeep this body.\n* TODO Undated\nKeep undated.\n* TODO Weekly planning\nSCHEDULED: <2026-11-10 09:00-10:00 .+2w>\nKeep repeat notes.\n';
  await api('Save', { id: state.id, path, source, revision: previous?.revision || '' });
  await page.clock.setFixedTime(new Date(2026, 10, 10, 9));
  await page.goto(base);
  await page.locator(`#tree [data-open="${path}"]`).click();
  await page.locator('#ribbon [data-view="agenda"]').click();
  await page.locator('#capture').click();
  await page.locator('#modal [name="title"]').fill('Plan the next release');
  assert.equal(await page.locator('#modal [name="date"]').getAttribute('type'), 'hidden', 'Only the calendar edits dates');
  assert.equal(await page.locator('.task-destination').getAttribute('open'), null, 'Location starts collapsed');
  const flow = await page.locator('.task-title-field, .task-date-picker, .task-planning, .task-destination, .task-repeat, .task-time-section').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().toJSON()));
  assert(flow.every((box, i) => i === 0 || box.y >= flow[i - 1].bottom), 'Title, calendar, planning, location, repeat and time follow a single column');
  assert(flow.every(box => box.x === flow[0].x && box.width === flow[0].width), 'Controls share a consistent alignment');
  assert(await page.locator('#modal-body').evaluate(el => el.scrollHeight <= el.clientHeight + 1), 'Default form fits a tall desktop');
  for (const [width, height] of [[1366, 768], [1280, 720], [1024, 640], [390, 700], [320, 568]]) {
    await page.setViewportSize({ width, height });
    assert(await page.locator('#modal-body').evaluate(el => el.scrollWidth <= el.clientWidth), `No horizontal overflow at ${width}×${height}`);
    const submit = await page.locator('#modal-submit').boundingBox();
    assert(submit.y + submit.height <= height, 'Primary action remains visible');
    assert(submit.x >= 0 && submit.x + submit.width <= width);
  }
  await page.setViewportSize({ width: 1280, height: 900 });
  const start = page.locator('#modal [name="time"]'), end = page.locator('#modal [name="endTime"]');
  await start.fill('09:15'); assert.equal(await end.inputValue(), '09:45', 'Start defaults to 30 minutes');
  await end.fill('10:45'); await start.fill('10:00'); assert.equal(await end.inputValue(), '11:30', 'An extended duration follows start changes');
  await page.getByRole('button', { name: '2 hours', exact: true }).click(); assert.equal(await end.inputValue(), '12:00');
  await end.fill('08:00'); assert.equal(await end.evaluate(el => el.checkValidity()), false);
  await page.locator('#modal-submit').click(); assert(await page.locator('#modal').isVisible(), 'Invalid time cannot save');
  await start.fill('23:45'); assert.equal(await end.inputValue(), '23:59', 'Near-midnight blocks remain on the same day');
  await start.fill('23:59'); assert.equal(await end.inputValue(), '', 'Last-minute starts never produce a backwards range');
  await page.getByRole('button', { name: 'Clear time', exact: true }).click();
  await start.fill('10:00'); assert.equal(await end.inputValue(), '10:30');
  const preset = page.getByRole('combobox', { name: 'Repeat', exact: true });
  await preset.selectOption('+1w'); assert.equal(await page.locator('[name="repeater"]').inputValue(), '+1w');
  await preset.selectOption('custom');
  await page.getByRole('spinbutton', { name: 'Repeat interval' }).fill('2');
  await page.getByRole('combobox', { name: 'Repeat from' }).selectOption('.+');
  assert.equal(await page.locator('[name="repeater"]').inputValue(), '.+2w');
  await page.getByRole('spinbutton', { name: 'Repeat interval' }).fill('0');
  assert.equal(await page.getByRole('spinbutton', { name: 'Repeat interval' }).evaluate(el => el.checkValidity()), false);
  await page.getByRole('spinbutton', { name: 'Repeat interval' }).fill('2');
  await page.getByRole('combobox', { name: 'Repeat unit' }).selectOption('h');
  await page.getByRole('button', { name: 'Clear time', exact: true }).click();
  assert.equal(await start.evaluate(el => el.checkValidity()), false, 'Hourly repeats require a start time');
  await page.getByRole('button', { name: 'No date', exact: true }).click();
  assert.equal(await page.locator('[name="date"]').inputValue(), '');
  assert.equal(await page.locator('[name="repeater"]').inputValue(), '');
  assert(await start.isDisabled() && await end.isDisabled() && await preset.isDisabled());
  await page.locator('[data-date-today]').click();
  assert(await start.isEnabled() && await preset.isEnabled());
  await page.locator('[data-date="2026-11-10"]').focus();
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('Space');
  assert.equal(await page.locator('[name="date"]').inputValue(), '2026-11-11', 'Calendar is keyboard operable');
  await page.keyboard.press('PageDown'); await page.keyboard.press('Space');
  assert.equal(await page.locator('[name="date"]').inputValue(), '2026-12-11', 'Keyboard navigation crosses months');
  await page.locator('[data-date-today]').click();
  await page.locator('.task-destination > summary').focus(); await page.keyboard.press('Enter');
  assert(await page.locator('.task-destination').evaluate(el => el.open), 'Enter expands Location without submitting');
  await page.getByRole('radio', { name: 'Beginning', exact: true }).check();
  await page.getByRole('radio', { name: 'Deadline', exact: true }).check();
  assert(await page.getByRole('radio', { name: 'Beginning', exact: true }).isChecked(), 'Placement and planning are independent');
  const input = page.locator('#modal input[name="path"]');
  await input.click();
  const list = page.locator('#' + await input.getAttribute('aria-controls'));
  assert(await list.evaluate(el => el.matches(':popover-open')), 'Dropdown uses the top layer');
  // Seed extra options in this isolated browser to exercise a long menu without
  // creating dozens of workspace files. Keyboard checks use the real options.
  const modal = page.locator('#modal-body');
  const initial = await modal.evaluate(el => el.scrollTop);
  for (let i = 0; i < 35; i++) await input.press('ArrowDown');
  assert.equal(await modal.evaluate(el => el.scrollTop), initial, 'Keyboard selection only scrolls the list');
  await list.evaluate(el => {
    for (let i = 0; i < 40; i++) { const row = document.createElement('div'); row.setAttribute('role', 'option'); row.textContent = 'Scroll boundary example ' + i; el.append(row); }
    el.scrollTop = el.scrollHeight;
  });
  const popup = await list.boundingBox();
  assert(await page.evaluate(({x,y,id}) => document.getElementById(id).contains(document.elementFromPoint(x,y)), {x:popup.x+20,y:popup.y+popup.height-10,id:await list.getAttribute('id')}), 'Dropdown is hit-testable above the scrolling form');
  await list.hover();
  await page.mouse.wheel(0, 700); await page.waitForTimeout(250);
  await page.mouse.wheel(0, 700); await page.waitForTimeout(250);
  assert.equal(await modal.evaluate(el => el.scrollTop), initial, 'Bottom boundary contains wheel scrolling');
  await list.evaluate(el => { el.scrollTop = 0; });
  await page.mouse.wheel(0, -700); await page.waitForTimeout(250);
  assert.equal(await modal.evaluate(el => el.scrollTop), initial, 'Top boundary contains wheel scrolling');
  await input.press('Escape');
  assert(await list.isHidden());
  await page.setViewportSize({width:390,height:700});
  const mobileSubmit = await page.locator('#modal-submit').boundingBox();
  assert(mobileSubmit.y + mobileSubmit.height <= 700, 'Mobile actions remain visible while the body scrolls');
  await input.click();
  const mobilePopup = await list.boundingBox();
  assert(mobilePopup.x >= 0 && mobilePopup.x + mobilePopup.width <= 390 && mobilePopup.y >= 0 && mobilePopup.y + mobilePopup.height <= 700, 'Dropdown stays inside the mobile viewport');
  await list.locator('[role="option"]').first().click();
  assert(await list.isHidden(), 'Selecting a portaled option closes the list');
  await page.setViewportSize({width:1280,height:900});
  await input.fill(path); await input.press('Tab');
  await page.getByRole('combobox', { name: 'Parent heading', exact: true }).fill('Projects');
  await page.getByRole('combobox', { name: 'Parent heading', exact: true }).press('Enter');
  assert.match(await page.locator('[data-task-location]').textContent(), /task-modal-polish.org › Projects/);
  await page.locator('.task-destination > summary').click();
  await page.getByRole('radio', { name: 'Scheduled', exact: true }).check();
  await preset.selectOption('+1w'); await start.fill('09:00');
  await page.locator('#modal-body').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({path:process.env.SCREENSHOT || join(tmpdir(), 'orbitalnote-task-modal-polish.png')});
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => !document.querySelector('.task-file-options'));
  assert.equal(await page.locator('.task-file-options').count(), 0, 'Closing the modal cleans up the overlays');
  await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('Task saved'));
  const saved = await api('Read', { id: state.id, path });
  assert.equal(saved.source, source.replace('** Existing', '** TODO Plan the next release\nSCHEDULED: <2026-11-10 09:00-09:30 +1w>\n** Existing'), 'Form values persist to Org without changing surrounding source');
  await page.locator(`#tree [data-open="${path}"]`).click();
  const editHeading = async text => {
    await page.locator('#source .org-heading').filter({ hasText: text }).locator('.heading-menu-button').click();
    await page.getByRole('button', { name: 'Edit task…', exact: true }).click();
    await page.locator('#modal[open]').waitFor();
  };
  await editHeading('Weekly planning');
  assert.equal(await page.locator('[name="repeater"]').inputValue(), '.+2w');
  assert.equal(await page.getByRole('combobox', { name: 'Repeat from' }).inputValue(), '.+');
  assert.equal(await end.inputValue(), '10:00', 'Editing preserves the existing duration');
  await start.fill('10:00'); assert.equal(await end.inputValue(), '11:00');
  await page.locator('#modal .modal-actions button[value="cancel"]').click();
  await editHeading('Undated');
  assert.equal(await page.locator('[name="date"]').inputValue(), '', 'Editing an undated task does not silently schedule it');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => !document.querySelector('#modal').open);
  assert.equal((await api('Read', { id: state.id, path })).source, saved.source);
  assert.deepEqual(errors, []);
  console.log('PASS single-column geometry, responsive actions, keyboard calendar, time defaults/extensions, recurrence, destination overlays, Org round-trip and edit preservation.');
} finally { await browser.close(); }
