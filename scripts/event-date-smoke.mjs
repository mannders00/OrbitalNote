// Run against a disposable app/dev workspace.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.BASE_URL || 'http://127.0.0.1:9255';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const api = async (method, data = {}) => { const response = await page.request.post(base + '/api', {data:{method,...data}}); assert(response.ok()); return response.json(); };
  const state = await api('Status'), path = 'event-date-smoke.org';
  const previous = state.files.some(f => f.path === path) ? await api('Read', {id:state.id,path}) : null;
  const source = '* Event\n:PROPERTIES:\n:ID: event-id\n:END:\nEvent notes\n** Child\nKeep this\n';
  await api('Save', {id:state.id,path,source,revision:previous?.revision || ''});
  await page.clock.setFixedTime(new Date(2026,9,18,9));
  await page.goto(base);
  await page.locator(`#tree [data-open="${path}"]`).click();
  await page.locator('#source .heading-menu-button').first().click();
  await page.getByRole('button',{name:'Set event date…',exact:true}).click();
  assert(await page.getByRole('radio',{name:'Event',exact:true}).isChecked());
  await page.locator('#modal [name="date"]').fill('2026-10-18');
  await page.locator('#modal [name="time"]').fill('10:00');
  await page.locator('#modal [name="endTime"]').fill('11:00');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#source').value.includes('<2026-10-18 10:00-11:00>'));
  const expected = source.replace(':END:\n', ':END:\n<2026-10-18 10:00-11:00>\n');
  assert.equal(await page.locator('#source').evaluate(el=>el.value), expected);
  await page.waitForFunction(() => document.querySelector('#save-state').textContent === 'Saved to disk');
  await page.locator('#ribbon [data-view="calendar"]').click();
  assert(await page.locator(`#calendar-grid [data-open="${path}"]`).count());
  await page.locator('#ribbon [data-view="agenda"]').click();
  const row = page.locator('.agenda-row').filter({has:page.locator(`[data-open="${path}"]`)}).first();
  await row.locator('[data-edit-task]').click();
  assert(await page.getByRole('radio',{name:'Event',exact:true}).isChecked(), 'Agenda recognizes the existing event type');
  assert.equal(await page.locator('#modal [name="time"]').inputValue(), '10:00');
  await page.locator('#modal [name="time"]').fill('10:30');
  const savedEdit = page.waitForResponse(response => response.url().endsWith('/api') && response.request().postDataJSON()?.method === 'Save');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => !document.querySelector('#modal').open);
  assert((await savedEdit).ok());
  assert.equal((await api('Read',{id:state.id,path})).source, expected.replace('10:00','10:30'));
  await page.locator('#capture').click();
  await page.locator('#modal [name="title"]').fill('Another event');
  await page.locator('#modal [name="path"]').fill(path);
  await page.locator('#modal [name="path"]').press('Tab');
  await page.getByRole('radio',{name:'Event',exact:true}).check();
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('Task saved'));
  const saved = (await api('Read',{id:state.id,path})).source;
  assert.match(saved, /\* Another event\n<2026-10-18>/);
  assert.doesNotMatch(saved, /TODO|SCHEDULED:|DEADLINE:/);
  assert.deepEqual(errors, []);
  console.log('PASS plain event creation via heading menu and task form, calendar/agenda display, event editing, and source preservation.');
} finally { await browser.close(); }
