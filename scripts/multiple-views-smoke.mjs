import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = process.env.BASE_URL || 'http://127.0.0.1:9291';
  await page.goto(base);
  const api = async (method, q = {}) => { const r = await page.request.post(base + '/api', { data: { method, ...q } }); assert.ok(r.ok(), await r.text()); return r.json(); };
  const { id, files } = await api('Status'), path = 'multiple-views.org';
  const old = files.some(f => f.path === path) ? await api('Read', { id, path }) : null;
  await api('Save', { id, path, revision: old?.revision || '', source: '* First\nOriginal paragraph.\n** Child\nNested body.\n' });
  await page.locator(`#tree [data-open="${path}"]`).click();
  const fileAction = async label => {
    await page.locator('#file-actions').click();
    await page.getByRole('dialog', { name: 'File actions', exact: true }).getByRole('button', { name: label, exact: true }).click();
  };
  await fileAction('Split right');
  assert.equal(await page.locator(`.ui-document[data-path="${path}"]`).count(), 2);
  const copyID = await page.locator('#document').getAttribute('data-view-id');
  const copy = page.locator(`.ui-document[data-view-id="${copyID}"]`);
  const primary = page.locator(`.ui-document[data-view-id="file:${path}"]`);
  await copy.locator('.ui-preview-toggle').click();
  await primary.locator('.ui-source').click();
  await primary.locator('.ui-source').evaluate(el => { el.setSelectionRange(el.value.length, el.value.length); el.focus(); });
  await page.keyboard.type('Shared edit.');
  await copy.locator('.ui-preview').getByText('Shared edit.', { exact: false }).waitFor();
  assert.equal(await copy.locator('.ui-source').evaluate(el => el.value), await primary.locator('.ui-source').evaluate(el => el.value));
  assert.equal(await copy.locator('.ui-panes').getAttribute('data-mode'), 'preview');
  await page.keyboard.press('Meta+z');
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-document[data-path="multiple-views.org"] .ui-source')].every(el => !el.value.includes('Shared edit.')));
  await page.keyboard.press('Meta+Shift+z');
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-document[data-path="multiple-views.org"] .ui-source')].every(el => el.value.includes('Shared edit.')));
  console.log('PASS split views share edits and retain independent reading modes');
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-save-state')].every(el => el.textContent === 'Saved to disk'));
  await page.reload();
  await copy.locator('.ui-preview').getByText('Shared edit.', { exact: false }).waitFor();
  assert.equal(await page.locator(`.ui-document[data-path="${path}"]`).count(), 2);
  await copy.locator('.ui-preview-toggle').click();
  await copy.locator('.ui-source').evaluate(el => { el.setSelectionRange(el.value.length, el.value.length); el.focus(); });
  await page.keyboard.type(' From second view.');
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-document[data-path="multiple-views.org"] .ui-source')].every(el => el.value.includes('From second view.')));
  console.log('PASS restored split and editing from the second view');
  await page.locator('#source').evaluate(el => { el.setSelectionRange(el.value.indexOf('Original'), el.value.indexOf('Original')); });
  await page.locator('#insert-content').click();
  const menu = page.getByRole('dialog', { name: 'Insert and format', exact: true });
  assert.equal(await menu.getByRole('button').first().textContent(), 'New task…');
  await menu.getByRole('button', { name: 'New task…', exact: true }).click();
  await page.locator('#modal [name="title"]').fill('Inserted task');
  await page.locator('#modal [data-date-clear]').click();
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#source').value.includes('* TODO Inserted task\nOriginal paragraph.'));
  console.log('PASS document New task inserts at cursor and preserves surrounding text');
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-save-state')].every(el => el.textContent === 'Saved to disk'));
  await page.locator(`[data-tab-close="file:${path}"]`).click();
  assert.equal(await page.locator(`.ui-document[data-path="${path}"]`).count(), 1);
  await page.locator('#source').evaluate(el => { el.setSelectionRange(el.value.length, el.value.length); el.focus(); });
  await page.keyboard.type(' After close.');
  await page.waitForFunction(() => document.querySelector('#save-state').textContent === 'Saved to disk');
  assert.ok((await api('Read', { id, path })).source.includes('After close.'));
  console.log('PASS closing original keeps remaining view editable and saves to the same file');
  await fileAction('Open in new tab');
  const secondID = await page.locator('#document').getAttribute('data-view-id');
  assert.ok(secondID.startsWith('copy:'));
  await fileAction('Rename or move…');
  const renamed = 'multiple-views-' + Date.now() + '.org';
  await page.locator('#modal [name="value"]').fill(renamed);
  await page.locator('#modal-submit').click();
  await page.waitForFunction(name => document.querySelectorAll(`.ui-document[data-path="${name}"]`).length === 2, renamed);
  await page.locator(`[data-tab-close="${secondID}"]`).click();
  assert.equal(await page.locator(`.ui-document[data-path="${renamed}"]`).count(), 1);
  assert.equal((await api('Read', { id, path: renamed })).source, await page.locator('#source').evaluate(el => el.value));
  console.log('PASS duplicate tab, shared file rename, and closing duplicate');
  await page.locator('#ribbon [data-view="agenda"]').click();
  await page.locator('#agenda-minimal').click();
  const date = await page.locator('#today-label').boundingBox(), pencil = await page.locator('#agenda-minimal').boundingBox();
  assert.ok(Math.abs(date.y + date.height / 2 - pencil.y - pencil.height / 2) < 2);
  assert.match(await page.locator('#today-label').textContent(), /\w+, \w+ \d+/);
  assert.deepEqual(errors, []);
  console.log('PASS minimal Agenda date/pencil alignment and extended date');
} finally { await browser.close(); }
