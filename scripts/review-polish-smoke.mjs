// Run against a disposable app/dev workspace.
import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
const base = process.env.BASE_URL || 'http://127.0.0.1:9256';
const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try {
  const page = await browser.newPage({viewport:{width:1400,height:950}});
  const api = async (method, args={}) => { const r=await page.request.post(base+'/api',{data:{method,...args}}); assert.ok(r.ok()); return r.json(); };
  const state=await api('Status'), path='polish-review.org';
  const prior=state.files.some(f=>f.path===path)?await api('Read',{id:state.id,path}):null;
  const source='\n* TODO Pending review\nSCHEDULED: <2026-09-30 Wed 09:00-10:00>\nBody\n* DONE Finished review\nSCHEDULED: <2026-09-30 Wed 11:00-12:00>\n* TODO Repeated review\nSCHEDULED: <2026-10-07 Wed +1w>\n:LOGBOOK:\n- State "DONE" from "TODO" [2026-09-30 Wed 10:00]\n:END:\n';
  await api('Save',{id:state.id,path,source,revision:prior?.revision||''});
  await page.clock.setFixedTime(new Date(2026,8,30,12));
  await page.goto(base); await page.locator('[data-filter="all"]').click();
  assert.ok(await page.locator('.agenda-row.completed').filter({hasText:'Finished review'}).isVisible());
  assert.ok(await page.locator('.agenda-row.completed').filter({hasText:'Repeated review'}).isVisible());
  await page.getByRole('button',{name:'Edit task: Pending review',exact:true}).click();
  await page.locator('#modal [name="title"]').fill('Pending revised');
  await page.locator('#modal [name="endTime"]').fill('10:30');
  await page.locator('#modal-submit').click();
  await page.locator('.agenda-entry').filter({hasText:'Pending revised'}).waitFor();
  assert.ok(await page.locator('#agenda').isVisible());
  assert.match((await api('Read',{id:state.id,path})).source,/09:00-10:30/);
  await page.locator('#tree [data-open="polish-review.org"]').click();
  const doc=page.locator('.ui-document[data-path="polish-review.org"]'), editor=doc.locator('[data-ui="source"]');
  await doc.waitFor({state:'visible'});
  await page.locator('#ribbon [data-view="settings"]').click(); await page.locator('#vi-mode').check();
  await page.locator('#monospace-mode').check(); await page.locator('#line-numbers').selectOption('absolute');
  await page.locator('[data-tab-select="file:polish-review.org"]').click();
  const normalSize=await editor.evaluate(el=>getComputedStyle(el).fontSize);
  assert.ok((await doc.locator('.org-heading').evaluateAll(els=>els.map(el=>getComputedStyle(el).fontSize))).every(size=>size===normalSize));
  assert.ok(await doc.locator('.cm-lineNumbers').isVisible());
  await editor.evaluate(el=>{el.focus();el.setSelectionRange(0,0);});
  await page.keyboard.press('j'); assert.equal(await editor.evaluate(el=>el.selectionStart),1);
  await page.keyboard.press('k'); assert.equal(await editor.evaluate(el=>el.selectionStart),0);
  await page.keyboard.press('j'); await page.keyboard.press('$');
  const caret=await editor.evaluate(el=>el.caretRect()), menu=await doc.locator('.heading-menu-button').first().boundingBox();
  assert.ok(caret.left<menu.x,'Caret belongs to text, not the heading menu');
  await page.keyboard.press('i');
  await page.keyboard.type('!');
  await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  const insertCaret=await doc.locator('.cm-cursor').first().boundingBox();
  assert.ok(insertCaret && insertCaret.x<menu.x-10,'Native insert caret belongs beside text');
  assert.match(await editor.evaluate(el=>el.value),/Pending revised!/);
  await page.keyboard.press('Escape');
  await doc.locator('.editor-heading-fold').first().click(); assert.ok(await doc.locator('.cm-foldPlaceholder').first().isVisible());
  assert.equal(await doc.locator('.cm-foldPlaceholder').first().textContent(),'…');
  await page.locator('#ribbon [data-view="calendar"]').click(); await page.locator('[data-calendar="week"]').click();
  assert.ok(await page.locator('.timed-event.completed').filter({hasText:'Finished review'}).isVisible());
  assert.ok(await page.locator('#calendar .completed').filter({hasText:'Repeated review'}).first().isVisible());
  await page.locator('#calendar').evaluate(el=>el.scrollTop=600);
  const header=await page.locator('.time-day-headers').boundingBox(), pane=await page.locator('#calendar').boundingBox(), allDay=await page.locator('.all-day-row').boundingBox();
  assert.ok(Math.abs(header.y-pane.y)<1); assert.ok(Math.abs(allDay.y-header.y-header.height)<1);
  assert.equal(await page.locator('.time-day.is-today').evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
  console.log('PASS: completed normal/repeating entries, first-line Vi motion, text caret, fold indicator, line numbers, uniform monospace sizes, pinned weekday/all-day rows and header-only highlight.');
} finally { await browser.close(); }
