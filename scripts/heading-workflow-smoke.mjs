// Run against a disposable app/dev workspace with the rebuilt editor bundle.
import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
const base = process.env.BASE_URL || 'http://127.0.0.1:9310';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const api = async (method, q = {}) => { const r = await page.request.post(base + '/api', { data: { method, ...q } }); assert.ok(r.ok(), await r.text()); return r.json(); };
  const state = await api('Status'), path = 'heading-workflow.org';
  const before = '* First\nFirst body\n* TODO Second\nSCHEDULED: <2026-10-09 Fri 13:00>\nSecond body\n- [ ] Parent\n  - [ ] Child\n    - Grandchild\n- Sibling\n* Third\nThird body\n';
  const old = state.files.some(f => f.path === path) ? await api('Read', { id: state.id, path }) : null;
  await api('Save', { id: state.id, path, source: before, revision: old?.revision || '' });
  await page.addInitScript(({ key, path }) => {
    if (sessionStorage.getItem('heading-workflow-seeded')) return;
    sessionStorage.setItem('heading-workflow-seeded', 'true');
    localStorage.setItem('org-vi-mode', 'true'); localStorage.setItem('org-right-sidebar', 'closed');
    localStorage.setItem('org-layout-' + key, JSON.stringify({ tree: { id: 'one', tabs: ['file:' + path], active: 'file:' + path }, focused: 'one' }));
  }, { key: state.key, path });
  await page.clock.setFixedTime(new Date(2026, 9, 9, 13, 30));
  await page.goto(base); const editor = page.locator('#source'); await editor.waitFor();
  await editor.evaluate(el => { el.foldHeading('fold-all'); el.jumpTo(el.value.indexOf('* TODO Second')); el.focus(); });
  await page.keyboard.type('O* Between'); await page.keyboard.press('Escape');
  assert.equal(await editor.evaluate(el => el.value), before.replace('* TODO Second', '* Between\n* TODO Second'));
  assert.equal(await editor.evaluate(el => el.getHeadingFolds().length), 3);
  await editor.evaluate(el => { el.foldHeading('unfold-all'); el.foldList(el.value.indexOf('- [ ] Parent'), true); });
  assert.equal(await editor.evaluate(el => el.listRanges().find(h => h.title.includes('Parent')).folded), true);
  await page.locator('#preview-toggle').click();
  const parent = page.locator('.ui-preview li').filter({ has: page.locator(':scope > .preview-list-fold') }).first();
  assert.equal(await parent.locator(':scope > .preview-list-fold').getAttribute('aria-expanded'), 'false');
  await parent.locator(':scope > .preview-list-fold').click();
  assert.equal(await editor.evaluate(el => el.listRanges().find(h => h.title.includes('Parent')).folded), false);
  console.log('PASS Vim O between folded headings; source/preview nested checklist folds');
  await page.locator('#preview-toggle').click();
  await page.locator('#file-actions').click();
  const menu = page.getByRole('dialog', { name: 'File actions', exact: true });
  assert.deepEqual((await menu.locator('button').allTextContents()).slice(0, 2), ['Fold all', 'Unfold all']);
  await menu.getByRole('button', { name: 'Split right', exact: true }).click();
  const right = await page.locator('#document').getAttribute('data-view-id');
  await page.locator('#source').evaluate(el => el.focus());
  await page.keyboard.press('Control+w'); await page.keyboard.press('h');
  assert.equal(await page.locator('#document').getAttribute('data-view-id'), 'file:' + path);
  await page.keyboard.press('Control+w'); await page.keyboard.press('l');
  assert.equal(await page.locator('#document').getAttribute('data-view-id'), right);
  await page.locator('#file-actions').click();
  await page.getByRole('dialog', { name: 'File actions', exact: true }).getByRole('button', { name: 'Split down', exact: true }).click();
  const bottom = await page.locator('#document').getAttribute('data-view-id');
  await page.locator('#source').evaluate(el => el.focus());
  await page.keyboard.press('Control+w'); await page.keyboard.press('k');
  assert.equal(await page.locator('#document').getAttribute('data-view-id'), right);
  await page.keyboard.press('Control+w'); await page.keyboard.press('j');
  assert.equal(await page.locator('#document').getAttribute('data-view-id'), bottom);
  await page.locator(`[data-tab-close="${bottom}"]`).click();
  await page.locator('#source').evaluate(el => el.jumpTo(el.value.indexOf('* TODO Second')));
  await page.locator('#source .heading-menu-button').nth(2).click();
  await page.getByRole('button', { name: 'Focus on heading', exact: true }).click();
  const focusID = await page.locator('#document').getAttribute('data-view-id');
  assert.ok(focusID.startsWith('copy:') && focusID !== right);
  assert.equal(await page.locator('#source').evaluate(el => el.getFocusRange().from), before.indexOf('* TODO Second') + '* Between\n'.length);
  assert.ok(!(await page.locator('#source').innerText()).includes('Third body'));
  await page.locator('#source').evaluate(el => { const at = el.value.indexOf('Second body'); el.replaceText('Focused body', at, at + 'Second body'.length); });
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-source')].every(el => el.value.includes('Focused body')));
  await page.locator('#source').evaluate(el => el.undo());
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-source')].every(el => el.value.includes('Second body')));
  await page.locator('#source').evaluate(el => el.replaceText('BAD', 0, 1));
  assert.ok((await page.locator('#source').evaluate(el => el.value)).startsWith('* First\nFirst body\n'));
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-save-state')].every(el => el.textContent === 'Saved to disk'));
  await page.reload();
  await page.getByRole('button', { name: 'Show whole file', exact: true }).waitFor();
  assert.equal(await page.locator('#document').getAttribute('data-view-id'), focusID);
  assert.ok(!(await page.locator('#source').innerText()).includes('Third body'));
  await page.locator(`.ui-document[data-view-id="file:${path}"] .ui-source`).evaluate(el => el.replaceText('Extra prefix\n', 0, 0));
  await page.locator(`[data-tab-select="${focusID}"]`).click();
  await page.waitForFunction(() => document.querySelector('#source').value.startsWith('Extra prefix'));
  assert.equal(await page.locator('#source').evaluate(el => el.getFocusRange().from), before.indexOf('* TODO Second') + '* Between\nExtra prefix\n'.length);
  assert.ok(!(await page.locator('#source').innerText()).includes('Extra prefix'));
  await page.getByRole('button', { name: 'Show whole file', exact: true }).click();
  assert.equal(await page.locator('#source').evaluate(el => el.getFocusRange()), null);
  console.log('PASS directional Vim split focus, heading-only shared editing/undo, protected surrounding source');
  await page.locator('#ribbon [data-view="agenda"]').click();
  const plannerGroup = await page.locator('#agenda').evaluate(el => el.closest('.tab-surface').dataset.ownerGroup);
  await page.locator('#agenda [data-open="heading-workflow.org"]').first().click();
  assert.equal(await page.locator('#agenda').isVisible(), true);
  assert.notEqual(await page.locator('#document').evaluate(el => el.closest('.tab-surface').dataset.ownerGroup), plannerGroup);
  console.log('PASS planner opens a new task tab in the other split');
  await page.waitForFunction(() => [...document.querySelectorAll('.ui-save-state')].every(el => el.textContent === 'Saved to disk'));
  await page.locator('#ribbon [data-view="agenda"]').click(); await page.locator('#capture').click();
  await page.locator('#modal [name="path"]').fill(path); await page.locator('#modal [name="parentLine"] option', { hasText: 'Second' }).waitFor({ state: 'attached' });
  await page.locator('#modal [name="parentLine"]').selectOption({ label: 'Second' });
  await page.locator('#modal [name="title"]').fill('Remembered child'); await page.locator('#modal-submit').click();
  await page.waitForFunction(() => !document.querySelector('#modal').open);
  await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('Task saved'));
  await page.locator('#capture').click();
  await page.waitForFunction(() => document.querySelector('[name="parentLine"]')?.selectedOptions[0]?.textContent === 'Second');
  assert.equal(await page.locator('#modal [name="path"]').inputValue(), path);
  await page.locator('#modal [name="parentLine"]').selectOption('start');
  await page.locator('#modal [name="title"]').fill('At beginning'); await page.locator('#modal-submit').click();
  for (let i = 0; i < 100; i++) { if ((await api('Read', { id: state.id, path })).source.startsWith('* TODO At beginning')) break; await page.waitForTimeout(50); }
  assert.ok((await api('Read', { id: state.id, path })).source.startsWith('* TODO At beginning'));
  const extra = 'unopened-planner.org', status = await api('Status');
  const extraOld = status.files.some(f => f.path === extra) ? await api('Read', { id: state.id, path: extra }) : null;
  await api('Save', { id: state.id, path: extra, revision: extraOld?.revision || '', source: '* TODO Unopened clock\nSCHEDULED: <2026-10-09 Fri 13:00>\n:LOGBOOK:\nCLOCK: [2026-10-09 Fri 13:15]\n:END:\n' });
  await page.locator('#agenda [data-open="unopened-planner.org"]').first().waitFor();
  await page.locator('#agenda [data-open="unopened-planner.org"]').first().click();
  assert.equal(await page.locator('#agenda').isVisible(), true);
  assert.equal(await page.locator('#document').getAttribute('data-path'), extra);
  assert.ok((await page.locator('#note-clock').textContent()).includes('1:15 PM'));
  await page.locator('#ribbon [data-view="settings"]').click();
  await page.locator('#calendar-time-format').selectOption('24');
  assert.ok((await page.locator('.ui-note-clock').first().textContent()).includes('13:15'));
  await page.locator('#ribbon [data-view="calendar"]').click();
  assert.ok((await page.locator('#calendar-clock').textContent()).includes('13:15'));
  assert.equal(await page.locator('.calendar-event').first().evaluate(el => getComputedStyle(el).userSelect), 'none');
  console.log('PASS previously unopened planner file, 12/24-hour running clocks, nonselectable calendar events');
  assert.deepEqual(errors, []);
  console.log('PASS task destination memory and beginning-of-file insertion');
} finally { await browser.close(); }
