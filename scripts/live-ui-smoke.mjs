// Run against a disposable app/dev workspace.
import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
const base=process.env.BASE_URL || 'http://127.0.0.1:9256';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try {
  const page=await browser.newPage({viewport:{width:1450,height:950}}), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const api=async(method,args={})=>{const r=await page.request.post(base+'/api',{data:{method,...args}});assert.ok(r.ok(),await r.text());return r.json();};
  const state=await api('Status'),path='live-ui.org',prior=state.files.some(f=>f.path===path)?await api('Read',{id:state.id,path}):null;
  const source='* TODO Live task\nSCHEDULED: <2026-10-01 Thu 13:00-14:00>\n** Nested target\nHidden child body\n* Other heading\nOther body\n'+Array.from({length:100},(_,i)=>`Paragraph ${i}.\n\n`).join('')+'- [ ] Bottom checklist\n';
  await api('Save',{id:state.id,path,source,revision:prior?.revision||''});
  await page.clock.setFixedTime(new Date(2026,9,1,13,15));
  await page.goto(base);await page.locator('#tree [data-open="live-ui.org"]').click();
  const doc=page.locator('.ui-document[data-path="live-ui.org"]'),editor=doc.locator('[data-ui="source"]');await doc.waitFor({state:'visible'});
  if(!await doc.locator('.ui-context').isVisible())await page.locator('#context-toggle').click();
  await editor.evaluate(el=>{el.focus();el.setSelectionRange(0,0);el.foldHeading('fold-all');});
  await doc.locator('[data-jump="3"]').click();
  await doc.locator('.org-jump-highlight').waitFor();
  assert.equal(await editor.evaluate(el=>el.value.slice(0,el.selectionStart).split('\n').length),3);
  assert.equal(await doc.locator('.editor-heading-fold[aria-label="Collapse heading: TODO Live task"]').count(),1);
  assert.ok(await doc.locator('.editor-heading-fold[aria-expanded="false"]').count()>0);
  await page.keyboard.press('ArrowRight');assert.equal(await doc.locator('.org-jump-highlight').count(),0);
  await editor.evaluate(el=>{el.foldHeading('unfold-all');el.focus();el.setSelectionRange(0,0);});
  assert.ok(await editor.evaluate(el=>{const r=el.caretRect();return r.bottom>r.top;}));
  await doc.locator('[data-ui="preview-toggle"]').click();
  const preview=doc.locator('.ui-preview');await preview.evaluate(el=>el.scrollTop=el.scrollHeight);
  const oldScroll=await preview.evaluate(el=>el.scrollTop);await doc.locator('.preview-checkbox').click();
  await page.waitForFunction(()=>document.querySelector('.ui-document[data-path="live-ui.org"] [data-ui="source"]').value.includes('[X] Bottom checklist'));
  await doc.locator('[data-ui="save-state"]').filter({hasText:'Saved to disk'}).waitFor();
  assert.ok(Math.abs(await preview.evaluate(el=>el.scrollTop)-oldScroll)<3,'preview checkbox preserves scroll');
  // Retain references across an autosave/refresh, including unchanged calendar geometry.
  await page.locator('#ribbon [data-view="agenda"]').click();await page.locator('[data-filter="all"]').click();
  await page.locator('.agenda-entry').filter({hasText:'Live task'}).evaluate(el=>window.agendaNode=el);
  await doc.locator('[data-jump="3"]').evaluate(el=>window.outlineNode=el);
  await page.locator('#ribbon [data-view="calendar"]').click();await page.locator('[data-calendar="day"]').click();
  assert.match(await page.locator('.time-labels').innerText(),/1:00 PM/);
  const block=page.locator('.time-block').filter({hasText:'Live task'});
  await block.evaluate(el=>window.calendarNode=el);
  await page.locator('#calendar').evaluate(el=>el.scrollTop=600);
  const scroll=await page.locator('#calendar').evaluate(el=>el.scrollTop);
  assert.equal(await page.locator('.calendar-now-line:not([hidden])').evaluate(el=>el.style.top),'795px');
  const note=await api('Read',{id:state.id,path});
  await api('Save',{id:state.id,path,revision:note.revision,source:note.source.replace('Live task','Live revised')});
  await page.locator('.timed-event').filter({hasText:'Live revised'}).waitFor();
  assert.ok(await page.evaluate(()=>window.agendaNode.isConnected && window.outlineNode.isConnected && window.calendarNode.isConnected));
  assert.equal(await page.locator('#calendar').evaluate(el=>el.scrollTop),scroll);
  await page.getByRole('button',{name:'Clock in to Live revised',exact:true}).click();
  await page.getByRole('button',{name:'Clock out of Live revised',exact:true}).waitFor();
  assert.ok(await page.locator('.timed-event.is-clocked').filter({hasText:'Live revised'}).isVisible());
  await page.getByRole('button',{name:'Mark Live revised as done',exact:true}).click();
  await page.locator('.timed-event.completed').filter({hasText:'Live revised'}).waitFor();
  assert.equal(await page.locator('#calendar').evaluate(el=>el.scrollTop),scroll);
  await page.locator('#ribbon [data-view="settings"]').click();await page.locator('#calendar-time-format').selectOption('24');
  await page.locator('#ribbon [data-view="calendar"]').click();assert.match(await page.locator('.time-labels').innerText(),/13:00/);
  await page.locator('#ribbon [data-view="agenda"]').click();
  assert.equal(await page.locator('.query-popup .query-chips').count(),1);
  assert.ok(await page.locator('.query-chips').isHidden());
  assert.deepEqual(errors,[]);
  console.log('PASS: minimal-unfold jumps/highlight, first-column caret, preview and calendar scroll, stable DOM refresh, calendar clock/completion, current-time marker and time-format setting.');
} finally {await browser.close();}
